#!/bin/bash
# build.sh: compile nodeguard_kern.o, generate nodeguard-maps.spec from the
# object, rehearse the exact production pin/attach sequence in a netns, and
# generate the per-host suricata.yaml files.
#
# Runs INSIDE a privileged Fedora 44 x86_64 container (see README):
#   docker run --rm --privileged -v <repo>:/work fedora:44 /bin/bash /work/build/build.sh
# The rehearsal needs a kernel with BTF and bpffs; the builder hosts provide
# both. No compiler ever lands on the production hosts.
set -euo pipefail

REPO=/work
OUT="$REPO/build/out"
mkdir -p "$OUT"

dnf -q install -y clang llvm libbpf-devel libxdp-devel xdp-tools bpftool \
    kernel-headers python3-pyyaml iproute >/dev/null

echo "== compile =="
clang -O2 -g -Wall -Werror -target bpf -D__x86_64__ \
    -c "$REPO/src/nodeguard_kern.c" -o "$OUT/nodeguard_kern.o"

echo "== generate map spec from the object (BTF is the source of truth) =="
# The object declares LIBBPF_PIN_BY_NAME, so it must be loaded through the
# same libxdp path production uses, with a throwaway pin root; a plain
# bpftool loadall+pinmaps conflicts with the declared pin paths.
mkdir -p /sys/fs/bpf
mountpoint -q /sys/fs/bpf || mount -t bpf bpf /sys/fs/bpf
# Clean any stray root-level pins from earlier failed runs (derived
# list written after spec generation; cover known names first).
for m in allow4 allow6 block4 block6 config stats stats2; do
    rm -f "/sys/fs/bpf/$m"
done
SPEC_PIN=/sys/fs/bpf/ngspec
rm -rf "$SPEC_PIN"
ip netns add ngspecns
cleanup_spec() {
    nsenter --net=/run/netns/ngspecns xdp-loader unload lo --all 2>/dev/null || true
    ip netns del ngspecns 2>/dev/null || true
    rm -rf "$SPEC_PIN"
}
trap cleanup_spec EXIT
nsenter --net=/run/netns/ngspecns ip link set lo up
nsenter --net=/run/netns/ngspecns xdp-loader load -m skb -p "$SPEC_PIN" lo "$OUT/nodeguard_kern.o"
# INVARIANT (ADR 0004/0007): the spec follows the OBJECT. The map list
# is derived from what libbpf actually pinned, asserted to contain the
# core six AND to equal the object's BTF-declared map set; a hardcoded
# list here once silently omitted a new map from the whole contract.
python3 - "$SPEC_PIN" "$OUT/nodeguard-maps.spec" "$OUT/nodeguard_kern.o" <<'PYEOF'
import json, subprocess, sys
pin, spec, obj = sys.argv[1], sys.argv[2], sys.argv[3]
import os
wanted = sorted(os.listdir(pin))
core = {"allow4", "allow6", "block4", "block6", "config", "stats"}
missing_core = core - set(wanted)
if missing_core:
    sys.exit(f"core maps missing from pins: {sorted(missing_core)}")
# INVARIANT (ADR 0007): declared maps come from the object's ".maps"
# DATASEC, and pinned-vs-declared must match in BOTH directions. This is
# the compensating control for the deliberately weakened identity check:
# a map missing its LIBBPF_PIN_BY_NAME line fails the BUILD, never ships.
btf = json.loads(subprocess.run(
    ["bpftool", "-j", "btf", "dump", "file", obj],
    capture_output=True, text=True, check=True).stdout)
types = {t["id"]: t for t in btf.get("types", [])}
declared = set()
for t in types.values():
    if t.get("kind") == "DATASEC" and t.get("name") == ".maps":
        for member in t.get("vars", []):
            var = types.get(member.get("type_id"), {})
            if var.get("name"):
                declared.add(var["name"])
if not declared:
    sys.exit("could not parse .maps DATASEC from BTF dump; refusing a "
             "vacuous pass")
unpinned = declared - set(wanted)
if unpinned:
    sys.exit(f"maps declared in BTF but not pinned by libbpf (missing "
             f"LIBBPF_PIN_BY_NAME?): {sorted(unpinned)}")
stray = set(wanted) - declared
if stray:
    sys.exit(f"pins with no BTF declaration: {sorted(stray)}")
rows = {}
for name in wanted:
    m = json.loads(subprocess.run(
        ["bpftool", "-j", "map", "show", "pinned", f"{pin}/{name}"],
        capture_output=True, check=True, text=True).stdout)
    rows[name] = (m["type"], m["bytes_key"], m["bytes_value"],
                  m["max_entries"], int(m.get("flags", 0)))
with open(spec, "w") as f:
    f.write("# Generated by build.sh from nodeguard_kern.o; do not edit.\n")
    f.write("# name type key_size value_size max_entries flags\n")
    for name in wanted:
        t, k, v, e, fl = rows[name]
        f.write(f"{name} {t} {k} {v} {e} {fl}\n")
print(open(spec).read())
PYEOF
cleanup_spec
trap - EXIT

echo "== rehearsal: production pin/attach sequence in a netns =="
PIN=/sys/fs/bpf/nodeguard
rm -rf "$PIN"
# 1. Pre-create pins from the spec exactly as nodeguard-maps.service does.
python3 "$REPO/bin/ngmap.py" create-maps --spec "$OUT/nodeguard-maps.spec"
# 2. Attach via xdp-loader against the pre-created pins (skb on lo inside a
#    netns; the mode differs from production but the pin-reuse path is the
#    same code).
ip netns add ngtest
trap 'ip netns del ngtest 2>/dev/null || true; rm -rf "$PIN"' EXIT
# The pin root is shared (bpffs is not per-netns), which matches production.
nsenter --net=/run/netns/ngtest ip link set lo up
nsenter --net=/run/netns/ngtest xdp-loader load -m skb -p "$PIN" lo "$OUT/nodeguard_kern.o"
nsenter --net=/run/netns/ngtest xdp-loader status lo
# 3. Map identity: the attached program must use the pre-created pins.
prog_id=$(nsenter --net=/run/netns/ngtest xdp-loader status lo | awk '$1=="=>" && $3=="nodeguard" {print $4}')
[ -n "$prog_id" ] || { echo "REHEARSAL FAIL: nodeguard not in dispatcher"; exit 1; }
prog_maps=$(bpftool prog show id "$prog_id" -j | python3 -c 'import json,sys; print(" ".join(str(i) for i in json.load(sys.stdin).get("map_ids", [])))')
MAPLIST=$(awk '!/^#/ && NF {print $1}' "$OUT/nodeguard-maps.spec")
for m in $MAPLIST; do
    mid=$(bpftool map show pinned "$PIN/$m" -j | python3 -c 'import json,sys; print(json.load(sys.stdin)["id"])')
    case " $prog_maps " in
    *" $mid "*) echo "identity ok: $m (id $mid)" ;;
    *) echo "REHEARSAL FAIL: attached prog does not reuse pinned $m"; exit 1 ;;
    esac
done
# 4. Exercise the encoders end to end against the live maps.
python3 "$REPO/bin/ngmap.py" block 203.0.113.7 --ttl 60
python3 "$REPO/bin/ngmap.py" list | grep -q 203.0.113.7
python3 "$REPO/bin/ngmap.py" set-config 0 41641
[ "$(python3 "$REPO/bin/ngmap.py" get-config 0)" = "41641" ]
python3 "$REPO/bin/ngmap.py" unblock 203.0.113.7
python3 "$REPO/bin/ngmap.py" sweep
# 4b. Crafted-packet sanity assertions: each anomaly increments its
# stats2 counter and the packet still PASSES (loopback delivery).
nsenter --net=/run/netns/ngtest python3 - <<'SANPY'
import socket, struct, subprocess, json, sys

def s2():
    out = subprocess.run(["python3", "/work/bin/ngmap.py", "stats2", "--json"],
                         capture_output=True, text=True, check=True).stdout
    return json.loads(out)

def tcp_probe(flags):
    # raw IPv4+TCP on loopback
    src = dst = "127.0.0.1"
    ip = struct.pack(">BBHHHBBH4s4s", 0x45, 0, 40, 0, 0, 64, 6, 0,
                     socket.inet_aton(src), socket.inet_aton(dst))
    tcp = struct.pack(">HHLLBBHHH", 12345, 9, 0, 0, 0x50, flags, 8192, 0, 0)
    s = socket.socket(socket.AF_INET, socket.SOCK_RAW, socket.IPPROTO_RAW)
    s.sendto(ip + tcp, (dst, 0))
    s.close()

def ttl_probe():
    ip = struct.pack(">BBHHHBBH4s4s", 0x45, 0, 28, 0, 0, 2, 17, 0,
                     socket.inet_aton("127.0.0.1"), socket.inet_aton("127.0.0.1"))
    udp = struct.pack(">HHHH", 12345, 9, 8, 0)
    s = socket.socket(socket.AF_INET, socket.SOCK_RAW, socket.IPPROTO_RAW)
    s.sendto(ip + udp, ("127.0.0.1", 0))
    s.close()

def frag4_probe():
    # first fragment: MF set, offset 0
    ip = struct.pack(">BBHHHBBH4s4s", 0x45, 0, 36, 1, 0x2000, 64, 17, 0,
                     socket.inet_aton("127.0.0.1"),
                     socket.inet_aton("127.0.0.1"))
    s = socket.socket(socket.AF_INET, socket.SOCK_RAW, socket.IPPROTO_RAW)
    s.sendto(ip + b"\x00" * 16, ("127.0.0.1", 0))
    s.close()

def frag6_probe():
    # IPv6 with a fragment header (nexthdr 44) via IPV6_HDRINCL
    IPV6_HDRINCL = 36
    ip6 = struct.pack(">IHBB16s16s", 0x60000000, 16, 44, 64,
                      socket.inet_pton(socket.AF_INET6, "::1"),
                      socket.inet_pton(socket.AF_INET6, "::1"))
    fh = struct.pack(">BBHI", 17, 0, 0, 1) + b"\x00" * 8
    s = socket.socket(socket.AF_INET6, socket.SOCK_RAW, socket.IPPROTO_UDP)
    s.setsockopt(socket.IPPROTO_IPV6, IPV6_HDRINCL, 1)
    s.sendto(ip6 + fh, ("::1", 0))
    s.close()

def stats_drops():
    out = subprocess.run(["python3", "/work/bin/ngmap.py", "stats", "--json"],
                         capture_output=True, text=True, check=True).stdout
    d = json.loads(out)
    return d["drop_v4"] + d["drop_v6"]

def continuity():
    # a real datagram must still be DELIVERED through the XDP hook
    rx = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    rx.bind(("127.0.0.1", 40404))
    rx.settimeout(3)
    tx = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    tx.sendto(b"nodeguard-continuity", ("127.0.0.1", 40404))
    data, _ = rx.recvfrom(64)
    rx.close(); tx.close()
    if data != b"nodeguard-continuity":
        sys.exit("SANITY REHEARSAL FAIL: continuity datagram corrupted")

drops_before = stats_drops()
before = s2()
tcp_probe(0x03)  # SYN+FIN
tcp_probe(0x06)  # SYN+RST
tcp_probe(0x00)  # NULL
tcp_probe(0x29)  # FIN+PSH+URG (XMAS)
ttl_probe()
frag4_probe()
frag6_probe()
continuity()
after = s2()
for key in ("tcp_synfin", "tcp_synrst", "tcp_null", "tcp_xmas", "ttl_low",
            "frag_v4", "frag_v6"):
    if after[key] <= before[key]:
        sys.exit(f"SANITY REHEARSAL FAIL: {key} did not increment "
                 f"({before[key]} -> {after[key]})")
if stats_drops() != drops_before:
    sys.exit("SANITY REHEARSAL FAIL: anomalous probes were DROPPED; the "
             "count-only contract is broken")
print("sanity counters increment, verdicts stayed PASS:",
      {k: after[k] for k in after})
SANPY

# 4c. Stats-read-failure drill, through the real kv contract: positive
# control first (all 8 slots + stats_read_fail=0), then with bpftool
# gone the kv output must carry stats_read_fail=1 and ZERO counter
# lines; never zeros.
mkdir -p /usr/local/lib/nodeguard /etc/nodeguard /run/nodeguard
cp /work/bin/nodeguard-lib.sh /work/bin/ngmap.py /usr/local/lib/nodeguard/
echo 'IFACE=lo' > /etc/nodeguard/nodeguard.env
kv_out=$(nsenter --net=/run/netns/ngtest bash /work/bin/nodeguard-status --kv)
for slot in pass drop_v4 drop_v6 pass_expired pass_allowlist pass_wgport pass_nonip pass_parsefail; do
    printf '%s\n' "$kv_out" | grep -q "^ng\.$slot=" || { echo "KV DRILL FAIL: $slot missing in positive control"; exit 1; }
done
printf '%s\n' "$kv_out" | grep -q "^ng.stats_read_fail=0$" || { echo "KV DRILL FAIL: stats_read_fail!=0 in positive control"; exit 1; }
mv /usr/sbin/bpftool /usr/sbin/bpftool.away
kv_out=$(nsenter --net=/run/netns/ngtest bash /work/bin/nodeguard-status --kv)
mv /usr/sbin/bpftool.away /usr/sbin/bpftool
printf '%s\n' "$kv_out" | grep -q "^ng.stats_read_fail=1$" || { echo "KV DRILL FAIL: stats_read_fail=1 not emitted"; exit 1; }
if printf '%s\n' "$kv_out" | grep -qE "^ng\.(pass|drop_v4|drop_v6)="; then
    echo "KV DRILL FAIL: counter lines emitted despite read failure"
    exit 1
fi
echo "read-fail drill: kv contract holds (fail flag, no counter lines)"

# 4d. Unreferenced-pin tolerance (rollback direction): an extra pin the
# object does not reference must not block load or identity.
bpftool map create "$PIN/zzz_extra" type array key 4 value 8 entries 1 name zzz_extra
nsenter --net=/run/netns/ngtest xdp-loader load -m skb -p "$PIN" lo "$OUT/nodeguard_kern.o"
second_id=$(nsenter --net=/run/netns/ngtest xdp-loader status lo | awk '$1=="=>" && $3=="nodeguard" {print $4}' | tail -1)
nsenter --net=/run/netns/ngtest xdp-loader unload lo -i "$second_id"
rm -f "$PIN/zzz_extra"
echo "unreferenced-pin rehearsal: load and unload clean"

# 5. Unload by id, never --all.
nsenter --net=/run/netns/ngtest xdp-loader unload lo -i "$prog_id"
echo "== rehearsal PASSED =="

echo "== per-host suricata.yaml =="
# HOSTS_DIR may point at a private overlay of host config dirs; real
# deployments keep their host dirs outside this public repo.
HOSTS_DIR="${HOSTS_DIR:-$REPO/hosts}"
for params in "$HOSTS_DIR"/*/suricata-params.json; do
    [ -f "$params" ] || continue
    hostdir=$(dirname "$params")
    python3 "$REPO/build/mkyaml.py" --stock "$REPO/build/suricata-stock.yaml" \
        --params "$params" --out "$hostdir/suricata.yaml"
done

echo "== template drift gate =="
python3 /work/zbx/gen-template.py --out /tmp/template-check.json
python3 /work/zbx/check_template.py --sample /work/zbx/sample-nodeguard.kv \
    --template /tmp/template-check.json \
    --baseline /work/templates/zabbix-nodeguard-template.json
echo "template drift gate passed"

sha256sum "$OUT/nodeguard_kern.o" | tee "$OUT/nodeguard_kern.o.sha256"
echo "== build complete =="
