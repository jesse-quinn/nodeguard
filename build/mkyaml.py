"""mkyaml.py: generate a host's suricata.yaml from the stock Fedora 44
suricata 8.0.6 config plus a per-host parameter file. Run at build time
(needs python3-pyyaml); the output is validated on-host with suricata -T
before first start.

The full stock file is parsed and re-serialized, so comments are lost; the
stock copy is kept beside the outputs for drift comparison against future
RPM updates.

Parameter file (JSON, lives in the host's config directory):
{
  "iface": "eth0",
  "home_net": "[192.0.2.0/24,100.64.0.0/10]",
  "threads": 4,
  "ring_size": 32768,
  "management_cpus": [1],
  "worker_cpus": ["4-7"],
  "bpf_filter": null,           // or e.g. "not (udp and port 41641)"
  "cluster_id": 99              // optional; MUST differ from any other
                                // af-packet capture on the same NIC, or
                                // the kernel fanout group splits flows
                                // between the two captures
}
"""

import argparse
import json
import sys

import yaml


def main():
    """Generate one host's suricata.yaml from the stock config and a params file.

    Reads the JSON parameter file and the stock suricata.yaml, overlays the
    per-host settings (HOME_NET, one or more af-packet capture interfaces,
    CPU affinity, alert-only EVE output, stream bypass, unix-command), and
    writes the merged YAML to --out for on-host validation with suricata -T.
    """
    ap = argparse.ArgumentParser()
    ap.add_argument("--stock", required=True)
    ap.add_argument("--params", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    with open(args.params) as f:
        h = json.load(f)
    required = ("home_net", "management_cpus", "worker_cpus")
    if "interfaces" not in h:
        required = required + ("iface", "threads", "ring_size")
    for req in required:
        if req not in h:
            sys.exit(f"mkyaml: {args.params} missing required key '{req}'")

    with open(args.stock) as f:
        cfg = yaml.safe_load(f)

    cfg["vars"]["address-groups"]["HOME_NET"] = h["home_net"]

    # Either a single-interface legacy params file, or "interfaces": a
    # list of per-interface dicts (iface, threads, cluster_id, ring_size,
    # optional bpf_filter). Every interface needs a DISTINCT cluster_id;
    # duplicate ids on one host join a shared fanout group and split
    # flows between captures.
    ifaces = h.get("interfaces") or [{
        "iface": h["iface"], "threads": h["threads"],
        "cluster_id": h.get("cluster_id", 99),
        "ring_size": h["ring_size"], "bpf_filter": h.get("bpf_filter"),
    }]
    seen_ids = set()
    afp_list = []
    for i in ifaces:
        cid = i.get("cluster_id", 99)
        if cid in seen_ids:
            sys.exit(f"mkyaml: duplicate cluster_id {cid} in {args.params}")
        seen_ids.add(cid)
        afp = {
            "interface": i["iface"],
            "threads": i["threads"],
            "cluster-id": cid,
            "cluster-type": "cluster_flow",
            "defrag": True,
            "tpacket-v3": True,
            "ring-size": i["ring_size"],
        }
        if i.get("bpf_filter"):
            afp["bpf-filter"] = i["bpf_filter"]
        afp_list.append(afp)
    cfg["af-packet"] = afp_list

    cfg["threading"] = {
        "set-cpu-affinity": True,
        "cpu-affinity": {
            "management-cpu-set": {"cpu": h["management_cpus"]},
            "worker-cpu-set": {
                "cpu": h["worker_cpus"],
                "mode": "exclusive",
                "prio": {"default": "medium"},
            },
        },
    }

    cfg["runmode"] = "workers"

    # EVE: alerts only, with the flow counters the responder's
    # anti-spoofing gate requires.
    for out in cfg["outputs"]:
        if "eve-log" in out:
            eve = out["eve-log"]
            eve["enabled"] = True
            eve["filetype"] = "regular"
            eve["filename"] = "eve.json"
            eve["types"] = [{"alert": {"metadata": True, "tagged-packets": False}}]
        elif "fast" in out:
            out["fast"]["enabled"] = False
        elif "stats" in out:
            out["stats"]["enabled"] = False

    cfg.setdefault("stream", {})["bypass"] = True
    cfg.setdefault("unix-command", {})["enabled"] = True

    with open(args.out, "w") as f:
        f.write("%YAML 1.1\n---\n")
        f.write(f"# Generated by nodeguard build/mkyaml.py from {args.params}\n")
        f.write("# and the stock suricata-8.0.6-1.fc44 suricata.yaml.\n")
        f.write("# Do not hand-edit on the host; regenerate and redeploy.\n")
        yaml.safe_dump(cfg, f, default_flow_style=False, sort_keys=False)
    print(f"wrote {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
